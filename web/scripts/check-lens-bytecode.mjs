#!/usr/bin/env node
/**
 * Drift gate for the deployless stream lens.
 *
 * Rebuilds src/OVRFLOStreamLens.sol under the default Foundry profile and
 * compares creation bytecode (bytecode.object) to the copy embedded in
 * web/lib/generated/lens-bytecode.ts. A lens edit that skips regeneration
 * cannot ship a stale eth_call payload.
 *
 * Fail the gate; do not warn. Patterned on check-ovrflo-stream-bytecode.mjs.
 */
import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { execFileSync } from "node:child_process";
import { compareBytecodes } from "./check-ovrflo-stream-bytecode.mjs";

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(__dirname, "../..");
const WEB_ROOT = resolve(__dirname, "..");
const SOURCE_REL = "src/OVRFLOStreamLens.sol";
const SOURCE_PATH = join(REPO_ROOT, SOURCE_REL);
const FOUNDRY_TOML = join(REPO_ROOT, "foundry.toml");
const ARTIFACT_REL = "out/OVRFLOStreamLens.sol/OVRFLOStreamLens.json";
const EMBEDDED_REL = "lib/generated/lens-bytecode.ts";
const EMBEDDED_PATH = join(WEB_ROOT, EMBEDDED_REL);

const EXPECTED_SOLC = "0.8.36";
const EXPECTED_RUNS = 200;
const EXPECTED_VIA_IR = true;

function fail(message) {
  console.error(`check-lens-bytecode: ${message}`);
  process.exit(1);
}

function sha256Bytes(buf) {
  return createHash("sha256").update(buf).digest("hex");
}

function bytecodeObject(field) {
  return typeof field === "string" ? field : field.object;
}

function parseDefaultProfile(toml) {
  const body = toml.split("[profile.default]")[1]?.split(/^\[/m)[0] ?? "";
  const solc = /^\s*solc\s*=\s*"([^"]+)"/m.exec(body)?.[1];
  const runsRaw = /^\s*optimizer_runs\s*=\s*(\d+)/m.exec(body)?.[1];
  const viaIrMatch = /^\s*via_ir\s*=\s*(true|false)/m.exec(body)?.[1];
  if (!solc || !runsRaw || !viaIrMatch) {
    fail("foundry.toml [profile.default] missing solc, optimizer_runs, or via_ir");
  }
  return {
    solc,
    optimizerRuns: Number(runsRaw),
    viaIr: viaIrMatch === "true",
  };
}

export function parseEmbeddedLens(text) {
  const bytecode = /export const LENS_CREATION_BYTECODE =\s*"(0x[0-9a-fA-F]+)"/.exec(
    text,
  )?.[1];
  const sourceSha256 = /sourceSha256:\s*"([0-9a-f]{64})"/.exec(text)?.[1];
  const solc = /solc:\s*"([^"]+)"/.exec(text)?.[1];
  const runsRaw = /optimizerRuns:\s*(\d+)/.exec(text)?.[1];
  const viaIrRaw = /viaIr:\s*(true|false)/.exec(text)?.[1];
  const abiJson = /export const ovrfloStreamLensAbi = (\[[\s\S]*\]) as const;/.exec(
    text,
  )?.[1];
  if (!bytecode || !sourceSha256 || !solc || !runsRaw || !viaIrRaw || !abiJson) {
    throw new Error("lens-bytecode.ts is missing provenance, bytecode, or ABI");
  }
  return {
    bytecode,
    sourceSha256,
    solc,
    optimizerRuns: Number(runsRaw),
    viaIr: viaIrRaw === "true",
    abi: JSON.parse(abiJson),
  };
}

export function formatStaleCreationMessage(result) {
  return [
    "check-lens-bytecode: embedded creation bytecode is stale",
    `  embedded sha256: ${result.committedHash} (${result.committedLen} bytes)`,
    `  rebuilt   sha256: ${result.rebuiltHash} (${result.rebuiltLen} bytes)`,
    "  regenerate with: node web/scripts/check-lens-bytecode.mjs --write",
  ].join("\n");
}

function renderLensBytecodeTs({ bytecode, abi, provenance }) {
  return `/* Generated by web/scripts/check-lens-bytecode.mjs. Do not edit. */

export const LENS_PROVENANCE = {
  source: "src/OVRFLOStreamLens.sol",
  sourceSha256: "${provenance.sourceSha256}",
  solc: "${provenance.solc}",
  optimizerRuns: ${provenance.optimizerRuns},
  viaIr: ${provenance.viaIr},
} as const;

export const LENS_CREATION_BYTECODE =
  "${bytecode}" as \`0x\${string}\`;

export const ovrfloStreamLensAbi = ${JSON.stringify(abi, null, 2)} as const;
`;
}

function parseArtifactMetadata(artifact) {
  const meta =
    typeof artifact.metadata === "string"
      ? JSON.parse(artifact.metadata)
      : artifact.metadata;
  const version = meta?.compiler?.version ?? "";
  const solc = version.split("+")[0];
  const viaIr = Boolean(meta?.settings?.viaIR);
  const optimizerRuns = meta?.settings?.optimizer?.runs;
  const optimizerEnabled = Boolean(meta?.settings?.optimizer?.enabled);
  return { solc, viaIr, optimizerRuns, optimizerEnabled, version };
}

function assertShippingSettings(label, settings) {
  if (settings.solc !== EXPECTED_SOLC) {
    fail(`${label} solc must be ${EXPECTED_SOLC} (got ${settings.solc})`);
  }
  if (settings.optimizerRuns !== EXPECTED_RUNS) {
    fail(`${label} optimizer_runs must be ${EXPECTED_RUNS} (got ${settings.optimizerRuns})`);
  }
  if (settings.viaIr !== EXPECTED_VIA_IR) {
    fail(`${label} via_ir must be true (got ${settings.viaIr})`);
  }
}

export function checkLensBytecode(options = {}) {
  const skipBuild = Boolean(options.skipBuild);
  const write = Boolean(options.write);
  const rebuiltOverride = options.rebuiltBytecode;
  const embeddedPath = options.embeddedPath ?? EMBEDDED_PATH;

  const profile = parseDefaultProfile(readFileSync(FOUNDRY_TOML, "utf8"));
  assertShippingSettings("foundry.toml [profile.default]", profile);

  if (!existsSync(SOURCE_PATH)) fail(`missing ${SOURCE_REL}`);
  const sourceSha256 = sha256Bytes(readFileSync(SOURCE_PATH));

  if (!skipBuild) {
    console.log("check-lens-bytecode: forge build (default profile, via-IR)…");
    execFileSync("forge", ["build", "--skip", "test", "--skip", "script"], {
      cwd: REPO_ROOT,
      stdio: "inherit",
    });
  }

  let rebuiltHex;
  let rebuiltAbi;
  if (rebuiltOverride) {
    rebuiltHex = rebuiltOverride;
    rebuiltAbi = options.rebuiltAbi;
  } else {
    const artifactPath = join(REPO_ROOT, ARTIFACT_REL);
    if (!existsSync(artifactPath)) fail(`rebuild artifact missing at ${ARTIFACT_REL}`);
    const artifact = JSON.parse(readFileSync(artifactPath, "utf8"));
    const meta = parseArtifactMetadata(artifact);
    if (!meta.optimizerEnabled) fail("rebuild artifact optimizer must be enabled");
    assertShippingSettings("rebuild artifact", meta);
    rebuiltHex = bytecodeObject(artifact.bytecode);
    rebuiltAbi = artifact.abi;
  }

  if (!rebuiltHex) fail("rebuilt creation bytecode is empty");

  const provenance = {
    sourceSha256,
    solc: EXPECTED_SOLC,
    optimizerRuns: EXPECTED_RUNS,
    viaIr: EXPECTED_VIA_IR,
  };

  if (write) {
    if (!rebuiltAbi) fail("--write needs the rebuilt ABI");
    const hex = rebuiltHex.startsWith("0x") || rebuiltHex.startsWith("0X")
      ? `0x${rebuiltHex.slice(2).toLowerCase()}`
      : `0x${rebuiltHex.toLowerCase()}`;
    writeFileSync(
      embeddedPath,
      renderLensBytecodeTs({ bytecode: hex, abi: rebuiltAbi, provenance }),
    );
    console.log(`check-lens-bytecode: wrote ${EMBEDDED_REL}`);
  }

  if (!existsSync(embeddedPath)) {
    fail(`missing ${EMBEDDED_REL} — run node web/scripts/check-lens-bytecode.mjs --write`);
  }

  let embedded;
  try {
    embedded = parseEmbeddedLens(readFileSync(embeddedPath, "utf8"));
  } catch (error) {
    fail(error instanceof Error ? error.message : String(error));
  }

  if (embedded.sourceSha256 !== sourceSha256) {
    fail(
      `source hash mismatch\n  stamped: ${embedded.sourceSha256}\n  source:  ${sourceSha256}`,
    );
  }
  if (embedded.solc !== EXPECTED_SOLC || embedded.optimizerRuns !== EXPECTED_RUNS || embedded.viaIr !== true) {
    fail(
      `provenance stamp must be solc ${EXPECTED_SOLC}, optimizer_runs ${EXPECTED_RUNS}, viaIr true`,
    );
  }

  const result = compareBytecodes(embedded.bytecode, rebuiltHex);
  if (!result.equal) {
    console.error(formatStaleCreationMessage(result));
    process.exit(1);
  }

  if (rebuiltAbi) {
    const embeddedAbi = JSON.stringify(embedded.abi);
    const rebuiltAbiJson = JSON.stringify(rebuiltAbi);
    if (embeddedAbi !== rebuiltAbiJson) {
      fail("embedded lens ABI drifted from the rebuilt OVRFLOStreamLens artifact");
    }
  }

  console.log(
    `check-lens-bytecode: ok — creation bytecode matches (${result.committedLen} bytes, sha256 ${result.committedHash})`,
  );
  return result;
}

const isDirect =
  process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1]);
if (isDirect) {
  const write = process.argv.includes("--write");
  const skipBuild = process.env.CHECK_LENS_SKIP_BUILD === "1";
  checkLensBytecode({
    write,
    skipBuild,
    rebuiltBytecode: process.env.CHECK_LENS_REBUILT_BYTECODE,
  });
}
